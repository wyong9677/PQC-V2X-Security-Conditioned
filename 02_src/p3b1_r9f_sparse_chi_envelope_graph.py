            if not frozen_vals or not full_vals:
                continue
            fbest = min(frozen_vals, key=lambda z: z[0])
            abest = min(full_vals, key=lambda z: z[0])
            frozen_by_q[q] = fbest[0]
            full_by_q[q] = abest[0]
            improve = fbest[0] - abest[0]
