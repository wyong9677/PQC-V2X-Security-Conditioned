def atomic_write(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields: list[str] = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                fields.append(key)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in rows:
            w.writerow({k: row.get(k, "") for k in fields})


def cells_intersecting_interval(axis: np.ndarray, lo: float, hi: float) -> np.ndarray:
    axis = np.asarray(axis, dtype=float)
    lo, hi = float(min(lo, hi)), float(max(lo, hi))
    if hi < axis[0] - 1e-12 or lo > axis[-1] + 1e-12:
        return np.empty(0, dtype=np.int64)
    lo = max(lo, float(axis[0]))
    hi = min(hi, float(axis[-1]))
    left = axis[:-1]
    right = axis[1:]
    mask = (right >= lo - 1e-12) & (left <= hi + 1e-12)
    return np.flatnonzero(mask).astype(np.int64)


def scalar_cell_index(axis: np.ndarray, x: float) -> tuple[int, bool]:
    axis = np.asarray(axis, dtype=float)
    valid = bool(x >= axis[0] - 1e-12 and x <= axis[-1] + 1e-12)
    idx = int(np.searchsorted(axis, x, side="right") - 1)
    idx = int(np.clip(idx, 0, len(axis) - 2))
    return idx, valid


def pending_descriptor_envelope(*, age: float, bar_a: float, bar_u: float,
                                q: int, R: int, Ts: float, J: float,
                                b0, p3a: dict, p2b: dict) -> dict:
    """Conservative pending descriptor envelope for the diagnostic countdown.

    The pending candidate is generated (R-q)*Ts before the current sample.
    Relative to the generation time of the currently adopted tuple, the elapsed
    propagation time is age - pending_age.  The acceleration interval uses the
    model's existing certified lower predictor plus the symmetric uncertainty
    structure declared in the manuscript.  The command interval is generated by
    the declared slew-rate bound.  This deliberately over-approximates omitted
    correlations, which is conservative for robust adoption analysis.
    """
    pending_age = (R - q) * Ts
    elapsed = float(age - pending_age)
    if elapsed < -1e-10:
        return {"valid": False, "reason": "PENDING_GENERATION_PRECEDES_ADOPTED_GENERATION"}
    elapsed = max(elapsed, 0.0)
    tau = float(p3a.get("predecessor", {}).get("tau", p2b["predecessor"]["tau"]))
    nominal_a = float(bar_u + (bar_a - bar_u) * math.exp(-elapsed / tau))
    lower = float(b0.predecessor_acceleration_lower(
        np.asarray([elapsed]), np.asarray([bar_a]), np.asarray([bar_u]),
        J, p3a, p2b,
    )[0])
    radius = max(nominal_a - lower, 0.0)
    a_lo = lower
    a_hi = nominal_a + radius
    sd = p2b["state_domain"]
    a_lo = max(float(sd["a_p_min"]), a_lo)
    a_hi = min(float(sd["a_p_max"]), a_hi)
    pred = p3a.get("predecessor", {})
    u_min = float(pred.get("command_min", sd.get("a_p_min", -8.0)))
    u_max = float(pred.get("command_max", sd.get("a_p_max", 3.0)))
    u_lo = max(u_min, float(bar_u - J * elapsed))
    u_hi = min(u_max, float(bar_u + J * elapsed))
    if a_lo > a_hi + 1e-12 or u_lo > u_hi + 1e-12:
        return {"valid": False, "reason": "EMPTY_DESCRIPTOR_ENVELOPE"}
    return {
        "valid": True,
        "pending_age_before_interval_s": float(pending_age),
        "candidate_age_if_completion_s": float(pending_age + Ts),
        "elapsed_from_adopted_generation_to_pending_generation_s": float(elapsed),
        "a_nominal": nominal_a,
        "a_lower": float(a_lo),
        "a_upper": float(a_hi),
        "u_lower": float(u_lo),
        "u_upper": float(u_hi),
    }


def descriptor_cell_indices(lookup_axes, fixed_values: tuple[float, float, float, float],
                            env: dict) -> tuple[np.ndarray, bool]:
    """Enumerate every 6-D lookup cell intersecting the chi rectangle.

    fixed_values=(v_f_next,v_p_next,a_f_next,candidate_age).  bar_a and bar_u
    range over the full pending descriptor envelope.  Taking the maximum of the
    already corner-maxed Bellman values over all intersected cells is a rigorous
    enclosure of the finite lookup representation for this rectangle.
    """
    vf1, vp1, af1, age1 = fixed_values
    fixed = []
    for axis, x in zip((lookup_axes[0], lookup_axes[1], lookup_axes[2]), (vf1, vp1, af1)):
        j, ok = scalar_cell_index(axis, x)
        if not ok:
            return np.empty(0, dtype=np.int64), False
        fixed.append(j)
    ba_cells = cells_intersecting_interval(lookup_axes[3], env["a_lower"], env["a_upper"])
    bu_cells = cells_intersecting_interval(lookup_axes[4], env["u_lower"], env["u_upper"])
    age_cell, age_ok = scalar_cell_index(lookup_axes[5], age1)
    if not age_ok or len(ba_cells) == 0 or len(bu_cells) == 0:
        return np.empty(0, dtype=np.int64), False
    shape = tuple(len(a) - 1 for a in lookup_axes)
    inds = []
    for iba in ba_cells:
        for ibu in bu_cells:
            inds.append(np.ravel_multi_index(
                (fixed[0], fixed[1], fixed[2], int(iba), int(ibu), age_cell), shape
            ))
    return np.asarray(sorted(set(int(x) for x in inds)), dtype=np.int64), True


def robust_requirement(*, i: int, q: int, action: float, data: dict,
                       h_flat: np.ndarray, R: int, r3, b0, r9e) -> dict:
    cfg, p1, p2b, p3a = data["eval_cfg"], data["p1"], data["p2b"], data["p3a"]
    vf, vp, af, bar_a, bar_u, age = [np.asarray(x, float) for x in data["eval_flat"]]
    Ts = float(data["Ts"])
    J = float(cfg["information_contract"]["slew_rate"])
    nt = int(cfg["one_step"]["trajectory_points"])
    times = np.linspace(0.0, Ts, nt)
    tau = float(p2b["follower"]["tau"])
    w = float(p1["uncertainty"]["follower_actuation_abs"])
    sd = p2b["state_domain"]
    speed_bound = float(sd["v_f_max"]) + float(sd["v_p_max"])
    lips = 0.5 * speed_bound * (Ts / (nt - 1))

    sl = slice(i, i + 1)
    ap_lower = b0.predecessor_acceleration_lower(
        age[sl], bar_a[sl], bar_u[sl], J, p3a, p2b
    )
    Pp, Vp, Ap, Up, _ = r3.predecessor_motion_with_stop(
        vp[sl], ap_lower, bar_u[sl], age[sl], times, J, p3a
    )
    Pf, Vf, Af, _ = r9e.generalized_follower_motion(
        vf[sl], af[sl], float(action), times, tau, w
    )
    closing = Pf - Pp
    step_loss = float(max(np.max(closing, axis=1)[0] + lips, 0.0))
    closing_end = float(Pf[0, -1] - Pp[0, -1])

    axes = data["lookup_axes"]
    defer_vals = [
        Vf[:, -1], Vp[:, -1], Af[:, -1], bar_a[sl], bar_u[sl], age[sl] + Ts
    ]
    didx, dvalid = r3.locate_cells(axes, defer_vals)
    if not bool(dvalid[0]):
        return {"valid": False, "reason": "DEFER_OUTSIDE_LOOKUP"}

    env = pending_descriptor_envelope(
        age=float(age[i]), bar_a=float(bar_a[i]), bar_u=float(bar_u[i]),
        q=int(q), R=int(R), Ts=Ts, J=J, b0=b0, p3a=p3a, p2b=p2b,
    )
    if not env.get("valid", False):
        return {"valid": False, "reason": env.get("reason", "INVALID_CHI")}

    c_age = float(env["candidate_age_if_completion_s"])
    c_cells, cvalid = descriptor_cell_indices(
        axes,
        (float(Vf[0, -1]), float(Vp[0, -1]), float(Af[0, -1]), c_age),
        env,
    )
    if not cvalid:
        return {"valid": False, "reason": "CHI_ENVELOPE_OUTSIDE_LOOKUP"}

    h = h_flat.reshape(data["lookup_shape"] + (R,))
    cmax = r3.cell_corner_max(h)
    cell_flat = [cmax[..., qq].reshape(-1) for qq in range(R)]

    # Completion output reveals authenticated content.  The preselected causal
    # adoption map may choose adopt/hold as a function of that output.  Since
    # hold is independent of chi, max_chi min(adopt(chi),hold) equals
    # min(max_chi adopt(chi), hold).
    robust_adopt = float(np.max(cell_flat[R - 1][c_cells]))
    hold = float(cell_flat[R - 1][int(didx[0])])
    completion = min(robust_adopt, hold)
    future = completion
    if q > 1:
        defer = float(cell_flat[q - 2][int(didx[0])])
        future = max(completion, defer)
    req = max(step_loss, closing_end + future, 0.0)
    projected = min(float(data["eval_fallback"][i]), req)
    return {
        "valid": bool(math.isfinite(projected)),
        "projected_required_gap_m": float(projected),
        "raw_required_gap_m": float(req),
        "step_loss_upper_m": step_loss,
        "closing_end_m": closing_end,
        "robust_adopt_future_m": robust_adopt,
        "hold_future_m": hold,
        "descriptor_cells": int(len(c_cells)),
        **env,
    }


def self_test() -> None:
    axis = np.asarray([0.0, 1.0, 2.0, 3.0])
    assert np.array_equal(cells_intersecting_interval(axis, 0.2, 1.8), np.asarray([0, 1]))
    assert np.array_equal(cells_intersecting_interval(axis, 1.0, 1.0), np.asarray([0, 1]))
    assert len(cells_intersecting_interval(axis, -2.0, -1.0)) == 0
    j, ok = scalar_cell_index(axis, 3.0)
    assert ok and j == 2
    # Causal identity used by robust completion branch.
    xs = [1.0, 4.0, 2.0]
    h = 2.5
    assert abs(max(min(x, h) for x in xs) - min(max(xs), h)) < 1e-12
    print("R9F_INTERNAL_SELF_TEST=PASS")


